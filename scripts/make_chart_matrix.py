"""Generate docs/CHART_COMPATIBILITY_MATRIX.md by actually calling the chart builder.

Usage (from the repository root):  python scripts/make_chart_matrix.py
The file is derived from data/charts.py, so it cannot drift from the code;
tests/test_docs_in_sync.py fails if the committed file is out of date.
"""
from __future__ import annotations

import itertools
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "phase4"))
warnings.simplefilter("ignore")

from data.charts import CHART_SPECS, CHART_TYPES, MAX_COLOR_GROUPS, ChartConfigError, build_chart  # noqa: E402

OUT = ROOT / "docs" / "CHART_COMPATIBILITY_MATRIX.md"


def sample_frame() -> pd.DataFrame:
    rng = np.random.default_rng(7)
    n = 80
    return pd.DataFrame({
        "category": rng.choice(["North", "South", "East", "West"], n),
        "group": rng.choice(["Widget", "Gadget", "Gizmo"], n),
        "many_values": [f"v{i % 50}" for i in range(n)],
        "measure": rng.gamma(2.0, 500.0, n).round(2),
        "measure2": rng.integers(1, 60, n),
        "date": pd.date_range("2024-01-01", periods=n, freq="D"),
        "flag": rng.choice([True, False], n),
    })


KIND = {"category": "category", "group": "category", "many_values": "high-cardinality category", "measure": "numeric",
        "measure2": "numeric", "date": "date", "flag": "boolean"}


def outcome(df, chart, **kw):
    try:
        build_chart(df, chart, **kw)
        return "ok", ""
    except ChartConfigError as exc:
        return "message", str(exc)


def scenarios(chart: str):
    """(label, kwargs) for each scenario that is meaningful for a chart type."""
    out = []
    if chart in ("Bar Chart", "Line Chart", "Area Chart"):
        for x, label in [("category", "category X"), ("date", "date X"), ("measure2", "numeric X"), ("flag", "boolean X"), ("many_values", "high-cardinality X")]:
            out.append((f"{label}, numeric Y", dict(x=x, y="measure", agg="Sum")))
        out += [("category X, numeric Y, colour by another category", dict(x="category", y="measure", color="group", agg="Sum")),
                ("category X, numeric Y, colour by 50-value column", dict(x="category", y="measure", color="many_values", agg="Sum")),
                ("category X, text Y, Sum", dict(x="category", y="group", agg="Sum")),
                ("category X, text Y, Count", dict(x="category", y="group", agg="Count")),
                ("X and Y the same column", dict(x="measure", y="measure", agg="Sum")),
                ("no X chosen", dict(y="measure", agg="Sum"))]
    elif chart == "Scatter Plot":
        out = [("numeric X, numeric Y", dict(x="measure2", y="measure")), ("numeric X, Y, colour by category", dict(x="measure2", y="measure", color="group")),
               ("category X, numeric Y", dict(x="category", y="measure")), ("date X, numeric Y", dict(x="date", y="measure")),
               ("X and Y the same column", dict(x="measure", y="measure")), ("text Y", dict(x="measure", y="category")),
               ("colour by 50-value column", dict(x="measure2", y="measure", color="many_values"))]
    elif chart == "Histogram":
        out = [("numeric column", dict(y="measure")), ("numeric column, colour by category", dict(y="measure", color="group")),
               ("text column", dict(y="category")), ("colour by 50-value column", dict(y="measure", color="many_values"))]
    elif chart in ("Box Plot", "Violin Plot"):
        out = [("numeric column only", dict(y="measure")), ("category X, numeric Y", dict(x="category", y="measure")),
               ("category X, numeric Y, colour by category", dict(x="category", y="measure", color="group")),
               ("date X (ignored)", dict(x="date", y="measure")), ("50-value category X", dict(x="many_values", y="measure")),
               ("text Y", dict(y="category"))]
    elif chart in ("Pie Chart", "Donut Chart"):
        out = [("category, row counts", dict(x="category")), ("category, numeric values, Sum", dict(x="category", y="measure", agg="Sum")),
               ("category, numeric values, Average", dict(x="category", y="measure", agg="Average")),
               ("category, text values, Sum", dict(x="category", y="group", agg="Sum")), ("no category chosen", dict(y="measure"))]
    else:
        out = [("all numeric columns", {}), ("two numeric columns", dict(columns=["measure", "measure2"])),
               ("one numeric column", dict(columns=["measure"])), ("text columns only", dict(columns=["category", "group"]))]
    return out


def render() -> str:
    df = sample_frame()
    lines = [
        "# Chart compatibility matrix",
        "",
        "_Generated by `scripts/make_chart_matrix.py` from the real chart builder (`phase4/data/charts.py`); "
        "do not edit by hand. `tests/test_docs_in_sync.py` fails if this file is stale._",
        "",
        "Every row below was run against a deterministic synthetic table. **Supported** = a figure was produced. "
        "**Message** = the builder refused the combination and returned the quoted user-facing text instead of crashing. "
        f"Colour/group columns with more than {MAX_COLOR_GROUPS} distinct values are refused by design.",
        "",
        "## What each chart accepts",
        "",
        "| Chart | X | Y | Colour / group | Aggregation |",
        "|---|---|---|---|---|",
    ]
    for chart in CHART_TYPES:
        s = CHART_SPECS[chart]
        lines.append(f"| {chart} | {s['x']} | {s['y']} | {s['color']} | {s['aggregation']} |")
    lines += ["", "## Scenario results", "", "| Chart | Scenario | Result | Message shown to the user |", "|---|---|---|---|"]
    totals = {}
    for chart in CHART_TYPES:
        ok = bad = 0
        for label, kw in scenarios(chart):
            result, message = outcome(df, chart, **kw)
            ok += result == "ok"
            bad += result != "ok"
            lines.append(f"| {chart} | {label} | {'Supported' if result == 'ok' else 'Message'} | {message or '—'} |")
        totals[chart] = (ok, bad)
    lines += ["", "## Summary", "", "| Chart | Scenarios tested | Supported | Refused with a message |", "|---|---:|---:|---:|"]
    for chart, (ok, bad) in totals.items():
        lines.append(f"| {chart} | {ok + bad} | {ok} | {bad} |")
    total_ok = sum(v[0] for v in totals.values())
    total_bad = sum(v[1] for v in totals.values())
    lines.append(f"| **All** | **{total_ok + total_bad}** | **{total_ok}** | **{total_bad}** |")
    lines += [
        "",
        "## Aggregation labels",
        "",
        "Bar, line, area, pie and donut charts accept `Sum`, `Average` (alias `Mean`), `Median`, `Count`, `Min`, `Max`. "
        "Any other label raises a friendly error. `Sum` of a group that is entirely missing stays missing (not 0).",
        "",
        "## Edge datasets (covered by `tests/test_charts.py::test_edge_datasets_never_crash`)",
        "",
        "Empty table, table with no columns, all-missing Y, constant Y, infinite values in Y, text mixed into a numeric column, "
        "high-cardinality X and a single row: every chart type returns either a figure or a message, never an exception.",
        "",
        "## Where the full cross-product is tested",
        "",
        "`tests/test_charts.py` sweeps chart type x X column x Y column x aggregation x colour column (about 190 test cases, all "
        "asserting *figure or friendly message, never an exception*), pins the expected outcome of 26 common combinations, and checks "
        "that drawn values equal a pandas groupby, that changing aggregation / colour / chart type changes the figure, and the original "
        "bar-chart regression (`region` X with `product` colour).",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
